// Merges tools/out/*.json into js/setups-data.js (the file the app loads).
const fs = require("fs");
const path = require("path");
const out = path.join(__dirname, "out");
const data = {};
["ultimate", "millers", "mafia"].forEach((rs) => {
  const f = path.join(out, "setups-" + rs + ".json");
  if (fs.existsSync(f)) data[rs] = JSON.parse(fs.readFileSync(f, "utf8"));
});
let bots = null;
const bf = path.join(out, "bots.json");
if (fs.existsSync(bf)) bots = JSON.parse(fs.readFileSync(bf, "utf8"));
const txt = "// Generated by tools/build-setups.js + tools/measure-bots.js + tools/merge-setups.js\n" +
  "// on " + new Date().toISOString().slice(0, 10) + ". Do not edit by hand.\n" +
  "// village = measured share of simulated games the village won (normal computers both sides).\n" +
  "window.WW_SETUPS = " + JSON.stringify(data) + ";\nwindow.WW_BOTS = " + JSON.stringify(bots) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "js", "setups-data.js"), txt);
console.log("wrote js/setups-data.js", Object.keys(data), bots ? "bots ok" : "no bots");
