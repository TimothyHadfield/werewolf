// "What does one extra role do?" — the 8-player base (2 wolves, Seer, Doctor,
// 4 villagers), then each extra role swapped in for one villager, Ultimate
// Werewolf rules, Normal computers on both sides. Writes js/roles-data.js.
// Run: node tools/measure-roles.js   (about a minute)
const fs = require("fs");
const path = require("path");
const W = require("../js/engine.js");
const GAMES = 4000;
const base = { wolf: 2, seer: 1, doctor: 1, villager: 4 };
const rows = [
  { add: null, setup: base },
  { add: "lycan", setup: { wolf: 2, seer: 1, doctor: 1, lycan: 1, villager: 3 } },
  { add: "minion", setup: { wolf: 2, seer: 1, doctor: 1, minion: 1, villager: 3 } },
  { add: "tanner", setup: { wolf: 2, seer: 1, doctor: 1, tanner: 1, villager: 3 } },
  { add: "prince", setup: { wolf: 2, seer: 1, doctor: 1, prince: 1, villager: 3 } },
  { add: "hunter", setup: { wolf: 2, seer: 1, doctor: 1, hunter: 1, villager: 3 } },
];
const out = rows.map((r, i) => {
  const rng = W.mulberry32(20261028 + i);
  let v = 0, t = 0;
  for (let k = 0; k < GAMES; k++) {
    const g = W.simulateGame(r.setup, { rng, opts: W.RULESETS.ultimate.opts, full: true });
    if (g.winner === "village") v++;
    if (g.tannerWon) t++;
  }
  const row = { add: r.add, setup: r.setup, village: Math.round((v / GAMES) * 1000) / 1000, tanner: r.setup.tanner ? Math.round((t / GAMES) * 1000) / 1000 : null, games: GAMES, uw: W.uwPoints(r.setup) };
  console.log((r.add || "base").padEnd(7), "village", row.village, row.tanner != null ? "tanner " + row.tanner : "", "UW", row.uw);
  return row;
});
fs.writeFileSync(path.join(__dirname, "..", "js", "roles-data.js"),
  "// Generated by tools/measure-roles.js on " + new Date().toISOString().slice(0, 10) + ". Do not edit by hand.\n" +
  "// One extra role swapped in for a villager on 8 players, Ultimate rules, Normal computers.\n" +
  "window.WW_ROLES = " + JSON.stringify({ rules: "ultimate", rows: out }) + ";\n");
